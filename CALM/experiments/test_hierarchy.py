#!/usr/bin/env python3
"""Does patching destroy the hierarchy HELM exists to model?

The central research risk in `../NEXT.md` §6: HELM's thesis is that hyperbolic
geometry matches the **token-level** hierarchy of language, and CALM compresses K
tokens into one vector. If the hierarchy lives below the patch boundary, a
HELM-CALM ends up with CALM's efficiency and no reason to be hyperbolic.

The experiment builds a language with a *known* hierarchy, so "did the model
learn the hierarchy" is measurable rather than a matter of interpretation.

**The data.** Tokens are the leaves of a balanced tree of depth D and branching
factor B, so the true distance between any two tokens is known by construction.
Sequences are generated by a random walk that mostly stays inside a subtree and
occasionally jumps to a cousin, which makes tokens that are close in the tree
also likely to co-occur -- the property a hierarchical language has.

**The knob that matters.** ``locality`` sets how far apart in the sequence
hierarchically-related tokens are:

* ``locality="within"``  -- related tokens are adjacent, so the signal lies
  *inside* a K=4 patch;
* ``locality="across"``  -- related tokens are >= 4 apart, so the signal spans
  patch boundaries.

If patching is harmful, it should hurt "within" far more than "across". If both
degrade equally, the cause is capacity, not patching.

**The measurements.**

1. *Hierarchy recovery* -- Spearman correlation between tree distance and
   representation distance over token pairs. This is the direct question.
2. *delta-hyperbolicity* -- Gromov's four-point condition on the learned
   representations, normalised by diameter. Lower means more tree-like. This is
   the property HELM's whole argument rests on.
3. *Predictive accuracy* -- so a model that has simply failed to learn is not
   mistaken for one that learned without hierarchy.

Usage: python CALM/experiments/test_hierarchy.py --steps 4000
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "CALM"))

from helm_calm import HelmCALM, PatchAutoencoder  # noqa: E402


# ----------------------------------------------------------------- the language

class HierarchicalLanguage:
    """A token vocabulary that is the leaf set of a balanced tree.

    Args:
        depth: tree depth; the vocabulary is ``branching ** depth``.
        branching: children per node.
        locality: ``"within"`` puts hierarchically-related tokens adjacent in the
            sequence, ``"across"`` puts them at least ``stride`` apart.
        stride: separation used by ``locality="across"``.
    """

    def __init__(self, depth: int = 3, branching: int = 4,
                 locality: str = "within", stride: int = 4):
        if locality not in ("within", "across"):
            raise ValueError(f"locality must be 'within' or 'across', got {locality!r}")
        self.depth = depth
        self.branching = branching
        self.locality = locality
        self.stride = stride
        self.vocab_size = branching ** depth
        self.paths = [self._path(t) for t in range(self.vocab_size)]

    def _path(self, token: int):
        """Root-to-leaf path of a token, as a tuple of child indices."""
        digits = []
        for _ in range(self.depth):
            digits.append(token % self.branching)
            token //= self.branching
        return tuple(reversed(digits))

    def tree_distance(self, a: int, b: int) -> int:
        """Path length through the lowest common ancestor."""
        path_a, path_b = self.paths[a], self.paths[b]
        shared = 0
        for x, y in zip(path_a, path_b):
            if x != y:
                break
            shared += 1
        return 2 * (self.depth - shared)

    def _sibling_of(self, token: int, generator) -> int:
        """A token sharing all but the last path element -- tree distance 2."""
        base = (token // self.branching) * self.branching
        return base + int(torch.randint(0, self.branching, (1,), generator=generator))

    def _cousin_of(self, token: int, generator) -> int:
        """A token from a different subtree -- a long-range jump."""
        return int(torch.randint(0, self.vocab_size, (1,), generator=generator))

    def sample(self, rows: int, length: int, seed: int = 0) -> torch.Tensor:
        """A batch of sequences carrying the hierarchical signal."""
        generator = torch.Generator().manual_seed(seed)
        out = torch.zeros(rows, length, dtype=torch.long)
        for row in range(rows):
            current = int(torch.randint(0, self.vocab_size, (1,), generator=generator))
            out[row, 0] = current
            for position in range(1, length):
                if self.locality == "within":
                    # Related to the immediately preceding token.
                    anchor = int(out[row, position - 1])
                else:
                    # Related to a token `stride` back, so the dependency has to
                    # cross patch boundaries at K = stride.
                    back = max(0, position - self.stride)
                    anchor = int(out[row, back])
                jump = torch.rand(1, generator=generator).item() < 0.2
                current = (self._cousin_of(anchor, generator) if jump
                           else self._sibling_of(anchor, generator))
                out[row, position] = current
        return out


# ------------------------------------------------------------------- measures

def spearman(x: torch.Tensor, y: torch.Tensor) -> float:
    """Rank correlation, without a scipy dependency."""
    def ranks(values):
        order = values.argsort()
        result = torch.zeros_like(values, dtype=torch.float64)
        result[order] = torch.arange(values.numel(), dtype=torch.float64)
        return result

    rx, ry = ranks(x.flatten()), ranks(y.flatten())
    rx = rx - rx.mean()
    ry = ry - ry.mean()
    denominator = (rx.norm() * ry.norm()).item()
    return 0.0 if denominator == 0 else float((rx @ ry).item() / denominator)


def delta_hyperbolicity(distances: torch.Tensor, samples: int = 20000,
                        seed: int = 0) -> float:
    """Gromov four-point delta, normalised by the diameter.

    For every sampled quadruple the two largest of the three pairings are
    compared; delta is half their gap. 0 means an exact tree, and larger means
    less tree-like. Normalising by the diameter makes it scale-free.
    """
    n = distances.size(0)
    generator = torch.Generator().manual_seed(seed)
    idx = torch.randint(0, n, (samples, 4), generator=generator)
    a, b, c, d = idx[:, 0], idx[:, 1], idx[:, 2], idx[:, 3]

    s1 = distances[a, b] + distances[c, d]
    s2 = distances[a, c] + distances[b, d]
    s3 = distances[a, d] + distances[b, c]
    stacked = torch.stack([s1, s2, s3], dim=-1)
    top2 = stacked.topk(2, dim=-1).values
    delta = (top2[:, 0] - top2[:, 1]) / 2
    diameter = distances.max()
    return float((delta.max() / diameter).item()) if diameter > 0 else 0.0


def lorentz_distances(points: torch.Tensor, curvature: float = 1.0) -> torch.Tensor:
    """Pairwise Lorentzian distance between on-manifold points."""
    time, space = points[:, :1], points[:, 1:]
    inner = space @ space.t() - time @ time.t()          # <x, y>_L
    argument = (-inner / curvature).clamp_min(1.0 + 1e-7)
    return (curvature ** 0.5) * torch.acosh(argument)


# ---------------------------------------------------------------- experiment

def train_model(language, patch_size, steps, lr=1e-3, seed=0, num_samples=8,
                dim=33, n_layers=3, length=32):
    """Train a HELM-CALM at the given patch size on the hierarchical language."""
    from tests._config import tiny_args

    torch.manual_seed(seed)
    args = tiny_args(vocab_size=language.vocab_size, dim=dim, n_layers=n_layers,
                     max_seq_len=length, original_seq_len=length)

    autoencoder = PatchAutoencoder(language.vocab_size, hidden=128, latent_size=32,
                                   patch_size=patch_size)
    ae_opt = torch.optim.AdamW(autoencoder.parameters(), lr=3e-3)
    corpus = language.sample(64, length, seed=seed)
    flat = corpus.reshape(-1)
    windows = flat[:(flat.numel() // patch_size) * patch_size].view(-1, patch_size)
    gen = torch.Generator().manual_seed(seed)
    for _ in range(800):
        rows = torch.randint(0, windows.size(0), (128,), generator=gen)
        loss, _ = autoencoder.elbo(windows[rows])
        ae_opt.zero_grad()
        loss.backward()
        ae_opt.step()
    with torch.no_grad():
        mean, _ = autoencoder.encode(windows)
        ae_accuracy = (autoencoder.decode(mean).argmax(-1) == windows).float().mean().item()

    model = HelmCALM(args, autoencoder, num_samples=num_samples)
    groups = model.parameter_groups()
    params = groups["euclidean"] + groups["manifold"]
    optimizer = torch.optim.AdamW(params, lr=lr)

    batches = [language.sample(2, length, seed=seed * 1000 + i) for i in range(16)]
    model.train()
    for step in range(steps):
        loss = model.loss(batches[step % len(batches)])
        optimizer.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(params, 1.0)
        optimizer.step()
        model.retract_manifold_parameters()

    model.eval()
    correct = total = 0
    with torch.no_grad():
        for tokens in batches:
            predicted, targets = model.predict_tokens(tokens, n_samples=32)
            correct += (predicted == targets).sum().item()
            total += targets.numel()
    return model, correct / total, ae_accuracy


def measure_hierarchy(model, language):
    """Recovery correlation and delta-hyperbolicity of the token embedding."""
    embedding = model.backbone.embed.embedding.detach()
    curvature = float(model.backbone.manifold_in.c)
    representation = lorentz_distances(embedding, curvature)

    tokens = torch.arange(language.vocab_size)
    tree = torch.tensor([[float(language.tree_distance(int(a), int(b)))
                          for b in tokens] for a in tokens])

    mask = ~torch.eye(language.vocab_size, dtype=torch.bool)
    recovery = spearman(tree[mask], representation[mask])
    return recovery, delta_hyperbolicity(representation), delta_hyperbolicity(tree)


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--steps", type=int, default=4000)
    parser.add_argument("--patches", type=int, nargs="+", default=[1, 4])
    parser.add_argument("--depth", type=int, default=3)
    parser.add_argument("--branching", type=int, default=4)
    parser.add_argument("--seeds", type=int, nargs="+", default=[0])
    cli = parser.parse_args()

    print("=" * 84)
    print("HIERARCHY -- does patching blur the structure HELM exists to model?")
    print("=" * 84)

    reference = HierarchicalLanguage(cli.depth, cli.branching)
    print(f"\nlanguage: balanced tree depth {cli.depth}, branching {cli.branching}"
          f" -> {reference.vocab_size} tokens")
    print(f"tree's own delta-hyperbolicity: "
          f"{delta_hyperbolicity(torch.tensor([[float(reference.tree_distance(a, b)) for b in range(reference.vocab_size)] for a in range(reference.vocab_size)])):.4f}"
          f"   (0 = an exact tree)\n")

    print(f"{'locality':>9s} {'K':>3s} {'AE recon':>9s} {'accuracy':>9s} "
          f"{'hierarchy recovery':>19s} {'delta':>7s}")
    print("-" * 84)
    results = {}
    for locality in ("within", "across"):
        language = HierarchicalLanguage(cli.depth, cli.branching, locality=locality)
        for patch in cli.patches:
            recs, accs, deltas = [], [], []
            for seed in cli.seeds:
                model, accuracy, ae_accuracy = train_model(
                    language, patch, cli.steps, seed=seed)
                recovery, delta, _ = measure_hierarchy(model, language)
                recs.append(recovery)
                accs.append(accuracy)
                deltas.append(delta)
            mean = lambda xs: sum(xs) / len(xs)
            results[(locality, patch)] = mean(recs)
            print(f"{locality:>9s} {patch:3d} {ae_accuracy:8.2%} {mean(accs):8.2%} "
                  f"{mean(recs):19.4f} {mean(deltas):7.4f}")

    print()
    for locality in ("within", "across"):
        if (locality, 1) in results and (locality, 4) in results:
            drop = results[(locality, 1)] - results[(locality, 4)]
            print(f"  {locality:>6s}-patch signal: hierarchy recovery falls "
                  f"{drop:+.4f} going from K=1 to K=4")
    print("\nA large fall for 'within' and a small one for 'across' would mean")
    print("patching destroys sub-patch hierarchy specifically. Similar falls mean")
    print("the cause is capacity or optimisation, not the patch boundary.")


if __name__ == "__main__":
    main()
